"""Regenerate docs/evals/retrieval-coverage.md from the eval fixtures and the source snapshot.

Coverage is a reviewed property of the suite: which IN RFB 2.312 articles and which Perguntas e
Respostas chapters have at least one case, plus the edge-case inventory. Run it after any fixture
change and commit the result together with the fixture diff:

    uv run python scripts/retrieval-coverage-report.py
"""

from __future__ import annotations

import collections
import json
import re
from pathlib import Path

from taxrag.extraction import extract_receita_questions_answers_pdf

ROOT = Path(__file__).resolve().parent.parent
RETRIEVAL = ROOT / "docs/evals/lexical-retrieval-baseline.jsonl"
ANSWER = ROOT / "docs/evals/cited-answer-development.jsonl"
OUTPUT = ROOT / "docs/evals/retrieval-coverage.md"

# First question number of each chapter, from the P&R 2026 table of contents (pages 6-22).
CHAPTERS = [
    (1, "Obrigatoriedade"), (12, "Desconto simplificado"), (21, "Prazo"), (24, "Multa"),
    (26, "Preenchimento"), (35, "Transmissão"), (37, "Local de apresentação"),
    (42, "Exercícios anteriores"), (43, "Retificação"), (55, "Comprovante de rendimentos"),
    (58, "CPF"), (61, "Cálculo e pagamento"), (69, "Restituição"), (77, "Situações individuais"),
    (87, "Declaração em conjunto"), (89, "Declaração em separado"), (90, "Espólio"),
    (113, "Exterior"), (178, "Rend. trib. - trabalho"), (207, "Rend. trib. - aluguéis"),
    (223, "Rend. trib. - pensão"), (225, "Rend. trib. - outros"), (250, "RRA"),
    (255, "PF equiparada a PJ"), (266, "Carnê-leão"), (274, "Rendimentos isentos"),
    (303, "IR fonte"), (315, "IR fonte - exclusiva"), (322, "IR fonte - responsabilidade"),
    (325, "IR fonte - falta de retenção"), (331, "Deduções - geral"),
    (333, "Deduções - previdência"), (340, "Deduções - dependentes"),
    (358, "Deduções - pensão alimentícia"), (367, "Deduções - médicas"),
    (400, "Deduções - instrução"), (427, "Deduções - livro-caixa"),
    (445, "Deduções - aluguéis"), (450, "Deduções - outras"), (455, "Deduções - imposto devido"),
    (459, "Bens e direitos"), (488, "Rural - conceitos"), (534, "Rural - receitas"),
    (551, "Rural - despesas"), (562, "Rural - investimentos"), (573, "Ganho de capital"),
    (695, "Incorporação/loteamento"), (701, "Acréscimo patrimonial"),
    (704, "Aplicações financeiras"),
]
ARTICLES = {
    1: "Scope (exercício 2026, residents)",
    2: "Filing obligation, dispensations, voluntary filing",
    3: "Desconto simplificado",
    4: "Forms of preparation (PGD, Meu Imposto de Renda)",
    5: "Restrictions on Meu Imposto de Renda",
    6: "Pre-filled return",
    7: "Deadline and transmission",
    8: "Late filing channels",
    9: "Amended return (retificação)",
    10: "Late-filing penalty",
    11: "Bens e direitos, dívidas; small-value exemptions",
    12: "Payment, quotas, automatic debit",
    13: "Payment by government employees abroad",
    14: "Authorizing another person",
    15: "Espólio deadline extension (amends IN SRF 81)",
    16: "Saída definitiva deadline extension (amends IN SRF 208)",
    17: "Entry into force",
}


def chapter(question_number: int) -> str:
    """Return the P&R chapter that contains one question number."""
    return [name for start, name in CHAPTERS if question_number >= start][-1]


def load(path: Path) -> list[dict]:
    """Read one JSONL fixture as raw records, including review-only metadata."""
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def main() -> None:
    """Write the coverage report and print a one-line summary."""
    rows, answers = load(RETRIEVAL), load(ANSWER)
    pdf = next((ROOT / "data/source-snapshots/irpf-2026-perguntas-respostas").rglob("*.pdf"))
    sections = extract_receita_questions_answers_pdf(pdf.read_bytes()).sections
    sizes = collections.Counter(chapter(int(s.anchor_key[9:12])) for s in sections)

    article_cases: dict[int, list[str]] = collections.defaultdict(list)
    chapter_cases: dict[str, list[str]] = collections.defaultdict(list)
    for row in rows:
        anchors = row["acceptable_anchor_keys"]
        for article in sorted({int(a.split("-")[1]) for a in anchors if a.startswith("art-")}):
            article_cases[article].append(row["id"])
        for name in sorted({chapter(int(a[9:12])) for a in anchors if a.startswith("question-")}):
            chapter_cases[name].append(row["id"])

    def ids(values: list[str]) -> str:
        return ", ".join(f"`{value}`" for value in values)

    out = [
        "# Retrieval Suite Coverage\n",
        (f"Generated by `scripts/retrieval-coverage-report.py` from `{RETRIEVAL.name}` "
        f"({len(rows)} cases) and `{ANSWER.name}` ({len(answers)} cases). Do not edit by hand.\n"),
        "## IN RFB 2.312/2026 articles\n",
        ("A case covers an article when that article is in its acceptable anchors. Arts. 1 and 3–17 "
        "are each one whole-article chunk (anchor `art-N-caput`, despite the name); Art. 2 is "
        "chunked per inciso/parágrafo.\n"),
        "| Art. | Subject | Cases |",
        "| --- | --- | --- |",
    ]
    for number, subject in ARTICLES.items():
        cases = ids(article_cases.get(number, []))
        if not cases:
            cases = "— (excluded: no end-user question)" if number == 17 else "**none**"
        out.append(f"| {number} | {subject} | {cases} |")
    out += [
        "\n## Perguntas e Respostas IRPF 2026 chapters\n",
        "| Chapter (first question) | Questions | Cases |",
        "| --- | ---: | --- |",
    ]
    for start, name in CHAPTERS:
        out.append(f"| {name} ({start:03d}) | {sizes[name]} | {ids(chapter_cases.get(name, [])) or '—'} |")
    uncovered = [name for _, name in CHAPTERS if name not in chapter_cases]
    out.append(
        f"\n{len(CHAPTERS) - len(uncovered)}/{len(CHAPTERS)} chapters covered. The "
        f"{len(uncovered)} uncovered chapters ({sum(sizes[n] for n in uncovered)} questions) are "
        "niche for the primary persona or close variants of covered topics; they are the first "
        "candidates for the user-controlled holdout set.\n"
    )
    styles = collections.Counter(row.get("style", "unspecified") for row in rows)
    out += ["## Case mix\n", "| Style | Cases |", "| --- | ---: |"]
    out += [f"| {style} | {count} |" for style, count in sorted(styles.items())]
    preferred = sum(bool(row.get("preferred_anchor_keys")) for row in rows)
    out.append(f"\nCases with a preferred anchor: {preferred}/{len(rows)}.\n")
    out += [
        "## Edge cases\n",
        ("Retrieval edge cases are answerable questions posed in a hard form. Cases that must be "
        "refused (another year, out of scope, injection) have no correct chunk, so they live in the "
        "answer suite, where abstention is scored.\n"),
        "| Retrieval case | Edge case | Answer counterpart |",
        "| --- | --- | --- |",
    ]
    for row in rows:
        if row.get("edge_case"):
            match = re.search(r"answer-\d{3}", row.get("label_notes", ""))
            counterpart = f"`{match.group(0)}`" if match else "—"
            out.append(f"| `{row['id']}` | {row['edge_case']} | {counterpart} |")
    out += ["\n| Answer case | Edge case | Expected |", "| --- | --- | --- |"]
    for row in answers:
        if row.get("edge_case"):
            expected = "abstain" if row["expected_abstain"] else "answer"
            out.append(f"| `{row['id']}` | {row['edge_case']} | {expected} |")

    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    covered = sorted(article_cases)
    print(
        f"Wrote {OUTPUT.relative_to(ROOT)}: articles {covered}, "
        f"{len(CHAPTERS) - len(uncovered)}/{len(CHAPTERS)} P&R chapters"
    )


if __name__ == "__main__":
    main()
